#[derive(Debug, Clone, Copy)]
pub enum InputEvent {
    /// Показать оверлей по координатам курсора (Ctrl+P или средняя кнопка мыши).
    Lookup { x: i32, y: i32 },

    /// Нажатие клавиши — скрыть оверлей. У клавиатуры нет осмысленных
    /// координат клика, поэтому это отдельный вариант от DismissClick.
    Dismiss,

    /// Нажатие любой другой кнопки мыши — скрыть оверлей, ЕСЛИ клик
    /// пришёлся не на сам оверлей. Клик по оверлею (drag-зона, кнопка
    /// bookmark) не должен его закрывать — иначе перетаскивание окна
    /// невозможно: мышь вниз на drag-зоне сразу же прятала бы оверлей.
    DismissClick { x: i32, y: i32 },
}
